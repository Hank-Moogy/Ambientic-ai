import test from 'node:test'
import assert from 'node:assert/strict'
import { fallbackTitle, isUserPromptRow, promptText, threadTitle } from '../src/main/thread-title.mjs'
import { SessionStore } from '../src/main/sessions.js'

test('names a thread after the intent the user typed', () => {
  assert.equal(threadTitle('Fix the thread naming bug in the sidebar.'), 'Fix the thread naming bug in the sidebar.')
})

test('drops the injected Ambientic context capsule', () => {
  const raw = '<ambientic-context mode="build">Project context: you are working on Agentbase…</ambientic-context>\nAdd a Telegram bridge'
  assert.equal(threadTitle(raw), 'Add a Telegram bridge')
})

test('drops system reminders, command wrappers and command output', () => {
  assert.equal(threadTitle('<system-reminder>Recalled memory: the user prefers…</system-reminder> Rename the thread'), 'Rename the thread')
  assert.equal(threadTitle('<command-name>loop</command-name><command-message>loop</command-message>'), '')
  assert.equal(threadTitle('<local-command-stdout>total 48\ndrwxr-xr-x 12 samori staff</local-command-stdout>'), '')
})

test('drops the local-command caveat preamble', () => {
  const raw = 'Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.\nShip the release'
  assert.equal(threadTitle(raw), 'Ship the release')
})

test('refuses machine output rather than naming a thread after it', () => {
  assert.equal(threadTitle('{"type":"tool_result","content":"ok"}'), '')
  assert.equal(threadTitle('diff --git a/src/main/index.js b/src/main/index.js'), '')
  assert.equal(threadTitle('src/main/index.js:1631:7  no-unused-vars'), '')
  assert.equal(threadTitle('/Users/samori/Documents/Agentbase'), '')
  assert.equal(threadTitle('npm ERR! code ELIFECYCLE'), '')
  assert.equal(threadTitle('/compact'), '')
  assert.equal(threadTitle('   '), '')
})

test('clips a long prompt to its first sentence', () => {
  const raw = 'Fix thread naming. It should work across every provider, and the rename must stick after a restart.'
  assert.equal(threadTitle(raw), 'Fix thread naming.')
})

test('reads only text parts, never a tool result payload', () => {
  assert.equal(promptText([{ type: 'text', text: 'Add offline badge' }]), 'Add offline badge')
  assert.equal(promptText([{ type: 'tool_result', content: '{"files":["a.js"]}' }]), '')
  assert.equal(promptText([{ type: 'image', source: {} }, { type: 'text', text: 'Look at this' }]), 'Look at this')
})

test('rejects transcript rows that are not user prompts', () => {
  assert.equal(isUserPromptRow({ type: 'user', message: { content: 'Hi' } }), true)
  assert.equal(isUserPromptRow({ type: 'assistant', message: { content: 'Hi' } }), false)
  assert.equal(isUserPromptRow({ type: 'user', isMeta: true, message: { content: 'Hi' } }), false)
  assert.equal(isUserPromptRow({ type: 'user', toolUseResult: {}, message: { content: 'Hi' } }), false)
  assert.equal(isUserPromptRow({ type: 'user', message: { content: [{ type: 'tool_result', content: 'out' }] } }), false)
})

test('falls back to a readable provider and project name', () => {
  assert.equal(fallbackTitle('Claude Code', 'Agentbase'), 'Claude Code · Agentbase')
  assert.equal(fallbackTitle('Codex', ''), 'Codex session')
})

function liveSession (store, id = 'session-1') {
  store.ingest({ event: 'session_start', session_id: id, agent: 'claude', cwd: '/tmp/project', tty: 'ttys001' })
  return id
}

test('a renamed thread is not relabelled by the summarizer or a provider index', () => {
  const store = new SessionStore()
  const id = liveSession(store)

  store.updateTask(id, 'Auto label', 'fp-1', 'model')
  assert.equal(store.list()[0].task, 'Auto label')

  store.updateTask(id, 'Thread naming fix', '', 'user')
  assert.equal(store.list()[0].task, 'Thread naming fix')

  store.updateTask(id, 'Another auto label', 'fp-2', 'model')
  assert.equal(store.list()[0].task, 'Thread naming fix')
  assert.equal(store.list()[0].taskSource, 'user')
  // The fingerprint still advances so the labeller stops recomputing.
  assert.equal(store.taskFingerprint(id), 'fp-2')
  assert.equal(store.taskLocked(id), true)
})

test('a rename survives rediscovery and restart', () => {
  const store = new SessionStore()
  const id = liveSession(store)
  store.updateTask(id, 'Thread naming fix', '', 'user')
  const persisted = store.taskCacheSnapshot()

  // Restart: a fresh store hydrates the cache after the provider index has
  // already supplied its own title for the same terminal.
  const restarted = new SessionStore()
  restarted.ingest({ event: 'session_start', session_id: id, agent: 'claude', cwd: '/tmp/project', tty: 'ttys001' })
  restarted.updateTask(id, 'Provider title', '', 'provider-index')
  restarted.hydrateTasks(persisted)
  assert.equal(restarted.list()[0].task, 'Thread naming fix')
  assert.equal(restarted.list()[0].taskSource, 'user')
})
